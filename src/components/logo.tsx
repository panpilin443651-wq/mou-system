import Image from "next/image";

// ============================================================================
// ตราสัญลักษณ์การยางแห่งประเทศไทย
// ============================================================================
// มีสองแบบ เพราะตราฉบับเต็มมีชื่อหน่วยงานไทย-อังกฤษอยู่ใต้รูป
// ซึ่งพอย่อลงมาเล็กๆ จะอ่านไม่ออกและกลายเป็นรอยเปื้อน
//
//   mark = เฉพาะรูปตราวงกลม  ใช้ที่แถบเมนูและไอคอนบนแท็บเบราว์เซอร์
//   full = ตราพร้อมชื่อหน่วยงาน ใช้ที่หน้าเข้าสู่ระบบและหัวเอกสารที่พิมพ์ออกกระดาษ
//
// ทั้งสองไฟล์มาจากต้นฉบับเดียวกัน ต่างกันแค่ viewBox ที่ครอบเฉพาะวงกลม
// ถ้าต้องเปลี่ยนตราใหม่ ให้ทับ public/logo.svg แล้วสร้าง logo-mark.svg ใหม่ตามเดิม
// ============================================================================

const SRC = {
  mark: "/logo-mark.svg",
  full: "/logo.svg",
} as const;

export function Logo({
  variant = "mark",
  size = 40,
  className = "",
}: {
  variant?: keyof typeof SRC;
  size?: number;
  className?: string;
}) {
  return (
    <Image
      src={SRC[variant]}
      alt="ตราสัญลักษณ์การยางแห่งประเทศไทย"
      width={size}
      height={size}
      // priority = โหลดรูปนี้ก่อนรูปอื่น เพราะอยู่บนสุดของหน้าและผู้ใช้เห็นทันที
      priority
      // ไฟล์ .svg ต้องข้ามตัวย่อรูปของ Next.js ไม่งั้นจะขึ้น error 400
      // (เป็นภาพลายเส้น ย่อแล้วไม่ได้เล็กลงอยู่แล้ว ข้ามไปได้เลย)
      unoptimized
      className={className}
    />
  );
}
